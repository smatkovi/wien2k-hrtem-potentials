def parse_cfg(cfg_path):
    """
    Reads ixchel crystruct.cfg (libconfig format).
    Returns layers list: ax, by, cz, z0, filename, atoms.
    atoms: name, Z, proj_x, proj_y (fractional UC coordinates),
           optional proj_z (for subslicing).
    """
    cfg = pylibconfig2.Config(Path(cfg_path).read_text())

    dim   = tuple(cfg.dim)   if hasattr(cfg, 'dim')   else (512, 512)
    ncell = tuple(cfg.NCELL) if hasattr(cfg, 'NCELL') else (8, 8)

    # stack_seq = "1(abcd)" → ['a','b','c','d']
    seq_str = cfg.stack_seq
    seq = list(seq_str[seq_str.index('(') + 1 : seq_str.index(')')])

    # Read layer definitions
    layer_defs = {}
    for label in seq:
        if label in layer_defs:
            continue
        ly = getattr(cfg.layers, label)

        atoms_list = []
        if hasattr(ly, 'atoms'):
            for at in ly.atoms:
                Z_val = int(at.Z)
                B_val = float(at.DW) if hasattr(at, 'DW') else ixchel_B(Z_val)
                for p in at.positions:
                    pos = list(p)
                    atom_entry = {
                        'name':   str(at.name),
                        'Z':      Z_val,
                        'B':      B_val,
                        'proj_x': float(pos[0]),
                        'proj_y': float(pos[1]),
                    }
                    if len(pos) >= 3:
                        atom_entry['proj_z'] = float(pos[2])
                    atoms_list.append(atom_entry)

        layer_defs[label] = {
            'ax': float(ly.size_uc.x),
            'by': float(ly.size_uc.y),
            'cz': float(ly.size_uc.z),
            'filename': str(ly.filename),
            'atoms': atoms_list,
        }

    # Stacking sequence → layer list with z0 offset
    layers = []
    z0 = 0.0
    for label in seq:
        ld = layer_defs[label]
        layers.append({
            'label': label, 'ax': ld['ax'], 'by': ld['by'],
            'cz': ld['cz'], 'z0': z0,
            'filename': ld['filename'], 'atoms': ld['atoms'],
        })
        z0 += ld['cz']

    return {'layers': layers, 'dim': dim, 'ncell': ncell, 'total_z': z0}


# ══════════════════════════════════════════════════════════════════════════════
# Geometry: derive in-plane vectors from the Miller index
# ══════════════════════════════════════════════════════════════════════════════

def inplane_vectors(v3):
    """Returns integer v1, v2 with v1·v3 = v2·v3 = 0 and v1×v2 ∥ v3.

    Algorithm:
      v1 = [-k, h, 0]           for v3=[h,k,l] with h≠0 or k≠0
      v1 = [1, 0, 0]            for v3=[0,0,l]
      v2 = v3 × v1              (integer, orthogonal to both)

    Proof:   v1·v3 = 0  (trivial)
             v2·v3 = (v3×v1)·v3 = 0  (scalar triple product)
             v1×v2 = v1×(v3×v1) = v3·|v1|²  ∥ v3
    """
    from math import gcd
    h, k, l = v3
    if h != 0 or k != 0:
        v1 = [-k, h, 0]
    else:
        v1 = [1, 0, 0]
    v2 = list(np.cross(v3, v1))
    # Divide by gcd → shortest integer vectors
    def shorten(v):
        g = gcd(gcd(abs(v[0]), abs(v[1])), abs(v[2]))
        return [x // g for x in v] if g > 0 else v
    return shorten(v1), shorten(v2)


def beam_frame(spanvec, v1, v2, v3):
    """Cartesian unit vectors ex, ey, ez for the projection geometry."""
    def unit(v):
        c = spanvec.T @ np.array(v, float)
        return c / np.linalg.norm(c)
    return unit(v1), unit(v2), unit(v3)


# ══════════════════════════════════════════════════════════════════════════════
# Line integration (arbitrary direction)
# ══════════════════════════════════════════════════════════════════════════════

def project_layer(field3d, spanvec, v1, v2, v3,
                  ax, by, cz, z0, nx_out, ny_out, n_steps=80):
    """
    Projects field3d along v3 for the layer [z0, z0+cz].
    Returns: V_proj [field unit · Å], shape (nx_out, ny_out).
    """
    M_inv  = np.linalg.inv(spanvec)
    ex, ey, ez = beam_frame(spanvec, v1, v2, v3)
    nX, nY, nZ = field3d.shape

    IX, IY = np.meshgrid(np.arange(nx_out), np.arange(ny_out), indexing='ij')
    x_base = (IX[:,:,None] / nx_out * ax * ex[None,None,:] +
               IY[:,:,None] / ny_out * by * ey[None,None,:])

    dt     = cz / n_steps
    t_vals = np.linspace(z0, z0 + cz, n_steps, endpoint=False) + dt / 2
    proj   = np.zeros((nx_out, ny_out))

    for t in t_vals:
        r_frac = np.einsum('ij,...j->...i',
                            M_inv,
                            x_base + t * ez[None,None,:]) % 1.0
        coords = np.array([r_frac[:,:,0].ravel() * nX,
                            r_frac[:,:,1].ravel() * nY,
                            r_frac[:,:,2].ravel() * nZ])
        proj += (map_coordinates(field3d, coords, order=1, mode='wrap')
                  .reshape(nx_out, ny_out) * dt)
    return proj


# ══════════════════════════════════════════════════════════════════════════════
# 3D Poisson
# ══════════════════════════════════════════════════════════════════════════════

def poisson3d(rho_Ang, dx, dy, dz):
    """∇²V = −C·ρ  → V [V].  Input: ρ [e/ų]."""
    rho_k = fftn(rho_Ang)
    kx = fftfreq(rho_Ang.shape[0], dx) * 2 * np.pi
    ky = fftfreq(rho_Ang.shape[1], dy) * 2 * np.pi
    kz = fftfreq(rho_Ang.shape[2], dz) * 2 * np.pi
    KX, KY, KZ = np.meshgrid(kx, ky, kz, indexing='ij')
    k2 = KX**2 + KY**2 + KZ**2
    k2[0,0,0] = 1.0
    Vk = POISSON_C * rho_k / k2
    Vk[0,0,0] = 0.0
    return np.real(ifftn(Vk))


# ══════════════════════════════════════════════════════════════════════════════
# Kirkland IAM  –  correct phase convention
# ══════════════════════════════════════════════════════════════════════════════

def projected_lorentzian(a, b, k2, zmin, zmax):
    """Projected Lorentzian term — exactly ixchel SliceStack.cpp lines 38–66.

    Analytic z integral of the 3D Lorentzian potential a/(k²+b)
    from zmin to zmax (relative to the atom at z=0).
    For zmin=−∞, zmax=+∞: yields 2·a/(k²+b).
    """
    sqrt_kb = np.sqrt(k2 + b)

    if not np.isfinite(zmin):
        f1 = 0.0
    elif zmin < 0:
        f1 = np.exp(2 * np.pi * zmin * sqrt_kb)
    else:
        f1 = np.exp(-2 * np.pi * zmin * sqrt_kb)

    if not np.isfinite(zmax):
        f2 = 0.0
    elif zmax < 0:
        f2 = np.exp(2 * np.pi * zmax * sqrt_kb)
    else:
        f2 = np.exp(-2 * np.pi * zmax * sqrt_kb)

    prefactor = a / (k2 + b)

    if zmin <= 0 and zmax <= 0:
        return prefactor * (f2 - f1)
    elif zmin >= 0 and zmax >= 0:
        return prefactor * (f1 - f2)
    else:                               # zmin < 0 < zmax
        return prefactor * (2.0 - f1 - f2)


def projected_gaussian(c, d, k2, zmin, zmax):
    """Projected Gaussian term — exactly ixchel SliceStack.cpp lines 68–95.

    Analytic z integral of the 3D Gaussian potential c·exp(−d·k²)
    from zmin to zmax (relative to the atom at z=0).
    For zmin=−∞, zmax=+∞: yields 2·c·exp(−d·k²).
    """
    if zmin == -np.inf:
        f1 = -1.0
    elif zmin == np.inf:
        f1 = 1.0
    else:
        f1 = erf(np.pi * zmin / np.sqrt(d))

    if zmax == -np.inf:
        f2 = -1.0
    elif zmax == np.inf:
        f2 = 1.0
    else:
        f2 = erf(np.pi * zmax / np.sqrt(d))

    return c * np.exp(-k2 * d) * (f2 - f1)


def featom_k2(Z, k2, fp, zmin=-np.inf, zmax=np.inf):
    """
    Electron scattering factor f_e(k²) [Å] with optional z integration limits.

    Exactly ixchel SliceStack.cpp featom() (lines 105–127):
        f_e = (1/2) · [Σ projectedLorentzian + Σ projectedGaussian]

    For zmin=−∞, zmax=+∞ (default) identical to the full projection:
        f_e = Σ a_i/(k²+b_i)  +  Σ c_i·exp(−d_i·k²)
    """
    p   = fp[Z]
    res = np.zeros_like(k2, dtype=float)
    for a_, b_ in zip(p['a'], p['b']):
        res += projected_lorentzian(a_, b_, k2, zmin, zmax)
    for c_, d_ in zip(p['c'], p['d']):
        res += projected_gaussian(c_, d_, k2, zmin, zmax)
    res /= 2.0      # ixchel convention (SliceStack.cpp line 124)
    return res


def kirkland_layer(atoms_layer, ax, by, Nu, Nv, fp, cz=None):
    """
    Kirkland IAM in Fourier space [1/Å].

    With subslicing (cz given and atom has 'proj_z'):
      zmin = −proj_z · cz,  zmax = (1−proj_z) · cz
      → analytic z integration over the layer (ixchel SliceStack.cpp lines 421–445).

    Without subslicing (cz=None or no proj_z):
      zmin = −∞, zmax = +∞ → full projection as before.

    B-factors come from atom['B'] (automatically via ixchel_B(Z) or cfg DW).
    Phase: exp(−2πi k·r) — same as ixchel (SliceStack.cpp line 445).
    """
    ixmid, iymid = Nu // 2, Nv // 2
    kxv = np.array([i if i < ixmid else i - Nu for i in range(Nu)], float)
    kyv = np.array([i if i < iymid else i - Nv for i in range(Nv)], float)
    KX, KY = np.meshgrid(kxv, kyv, indexing='ij')

    k2    = KX**2 / ax**2 + KY**2 / by**2      # [Å⁻²]
    k2max = 1.0 / max(2*ax/Nu, 2*by/Nv)**2
    mask  = k2 <= k2max
    scale = float(Nu * Nv) / (ax * by)
    pix   = np.zeros((Nu, Nv), dtype=complex)

    for at in atoms_layer:
        Z = at['Z']
        if Z not in fp:
            print(f"    WARNING: Z={Z} ({at['name']}) not in fparams – skipped")
            continue
        B  = at['B']

        # Subslicing: finite z limits if the atom has a z coordinate
        proj_z = at.get('proj_z', None)
        if cz is not None and proj_z is not None:
            zmin = -proj_z * cz
            zmax = (1.0 - proj_z) * cz
        else:
            zmin, zmax = -np.inf, np.inf

        fe = featom_k2(Z, k2, fp, zmin, zmax) * np.exp(-B * k2)
        phase = np.exp(-2j * np.pi * (KX * at['proj_x'] + KY * at['proj_y']))
        pix  += mask * scale * fe * phase

    return np.real(np.fft.ifft2(pix))   # [1/Å]


# ══════════════════════════════════════════════════════════════════════════════
# TIFF output (ixchel format, 3 directories)
# ══════════════════════════════════════════════════════════════════════════════

def write_ixchel_tiff(filename, data_yx):
    """
    Writes a float32 TIFF in ixchel format:
      Dir 0: RGB preview (uint8)
      Dir 1: float32 data
      Dir 2: checksums (uint32, empty)
    data_yx: shape (Nv, Nu) = (ny, nx) — rows = y, columns = x.
    """
    Path(filename).parent.mkdir(parents=True, exist_ok=True)
    data = data_yx.astype(np.float32)
    vmin, vmax = float(data.min()), float(data.max())
    if vmax == vmin: vmax = vmin + 1e-6
    preview     = np.clip((data-vmin)/(vmax-vmin)*255, 0, 255).astype(np.uint8)
    preview_rgb = np.stack([preview, preview, preview], axis=-1)
    meta        = np.zeros((1, 2), dtype=np.uint32)
    with tifffile.TiffWriter(filename) as tfw:
        tfw.write(preview_rgb, photometric='rgb',        contiguous=False)
        tfw.write(data,        photometric='minisblack', contiguous=False)
        tfw.write(meta,        photometric='minisblack', contiguous=False)
    print(f"    → {filename}  [{vmin:.4g} … {vmax:.4g}] 1/Å")


