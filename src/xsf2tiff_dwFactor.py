def read_xsf(filename):
    """Reads 3ddens XSF. Density: e/Bohr³. Coordinates: Å."""
    with open(filename) as f:
        lines = f.readlines()
    primvec = None
    atoms   = []
    i = 0
    while i < len(lines):
        tok = lines[i].strip()
        if tok == 'PRIMVEC':
            primvec = np.array([[float(x) for x in lines[i+k+1].split()]
                                for k in range(3)])
            i += 4; continue
        if tok == 'PRIMCOORD':
            n = int(lines[i+1].split()[0])
            for k in range(n):
                p = lines[i+2+k].split()
                atoms.append({'Z': int(p[0]),
                               'cart': np.array([float(x) for x in p[1:4]])})
            i += 2+n; continue
        if 'DATAGRID_3D' in tok and 'END' not in tok and 'BLOCK' not in tok:
            i += 1
            nx, ny, nz = [int(x) for x in lines[i].split()[:3]]; i += 1
            origin  = np.array([float(x) for x in lines[i].split()]); i += 1
            spanvec = np.array([[float(x) for x in lines[i+k].split()]
                                 for k in range(3)]); i += 3
            vals = []
            while i < len(lines) and 'END_DATAGRID' not in lines[i]:
                vals.extend(float(x) for x in lines[i].split()); i += 1
            data = np.array(vals, dtype=np.float64).reshape(nx, ny, nz)
            break
        i += 1
    if primvec is None:
        primvec = spanvec
    return {'data': data, 'spanvec': spanvec, 'origin': origin,
            'shape': (nx, ny, nz), 'atoms': atoms,
            'dx': np.linalg.norm(spanvec[0]) / nx,
            'dy': np.linalg.norm(spanvec[1]) / ny,
            'dz': np.linalg.norm(spanvec[2]) / nz}


def read_struct_z2sym(filename):
    """Returns dict Z → element symbol from a WIEN2k .struct file.
    Parses the fixed-width format (same column widths as crystruct)."""
    z2sym = {}
    with open(filename) as f:
        lines = f.readlines()
    i = 4  # first 4 lines: title, lattice type, mode, lattice constants
    while i < len(lines):
        if lines[i].startswith('ATOM'):
            mult = int(lines[i + 1][15:17])       # "          MULT= 2"
            i += 1 + mult                          # skip equivalent positions
            name = lines[i][0:10].split()[0]       # "Ti        NPT=..."
            Z = int(float(lines[i][55:60]))        # "   Z: 22.0"
            z2sym[Z] = name
            i += 4                                 # atom line + 3 ROTLOC lines
        else:
            i += 1
    return z2sym


